/* TencBase.cpp -- BOX3D1..7 自定义位网络密码（tencrypt_new 复刻）
   与 secagent 二进制逐字节对拍还原（2026-08-10）。

   算法结构（由反汇编 + unicorn 运行时对拍确认）：
   - CBOX（DWARF：struct _stBOX，sizeof 20）：pUp/pDown/pLeft/pRight 四个
     邻居指针 + Value 字节；BOX3Dn 在栈上布 8n 个 CBOX。
   - 初始化：buf 的 8n 位按每函数固定的 IN 置换写入各盒 Value（部分位取反）。
   - 每个 key 字节按固定位序做 ~15..21 次位测试；每位选中"then/else"两组
     "沿邻居链轮转"变换（方向 up/down/left/right，可选取反），轮转覆盖该
     方向的整条环（4 盒环或 8 盒环）。
   - bnec=1 正向读 key[0..keylen-1]，bnec=0 反向读 key[keylen-1..0]。
   - 写回：按与 IN 相同的置换（OUT=IN）把各盒 Value 零/非零写回 buf 位。
   全部 7 个函数与 oracle 随机输入逐字节一致（见验证）。 */

#include "inc/TencBase.h"

namespace {

/* CBOX -- 由 secagent DWARF 提取（struct _stBOX，sizeof 20）：
   pUp@0 / pDown@4 / pLeft@8 / pRight@12 / Value@16。
   BOX3Dn 在栈上布 8n 个 CBOX，邻居指针构成若干 4/8 盒环；
   每次"轮转"沿 dir 环传播 Value（可选取反）。本实现以数组
   等价描述同一网络（盒号 = 数组下标，方向表 = 邻居指针）。 */
struct CBOX {
    int pUp;
    int pDown;
    int pLeft;
    int pRight;
    unsigned char Value;
};

struct Walk {
    unsigned char term;   /* 环上终点盒（= 保存值盒） */
    unsigned char dir;    /* 0=up 1=down 2=left 3=right */
    unsigned char inv;    /* 1=取反传播 */
};

/* 沿 dir 方向轮转 term 所在环：每盒新值 = 旧邻居值(可取反) */
void box_rot(unsigned char *v, int n, int term, int dir, int inv,
             const int *UP, const int *DOWN, const int *LEFT, const int *RIGHT) {
    const int *mp = dir == 0 ? UP : dir == 1 ? DOWN : dir == 2 ? LEFT : RIGHT;
    unsigned char old[64];
    int cycle[64];
    int nc = 0, x = term, i;
    for (i = 0; i < n; i++)
        old[i] = v[i];
    do {
        cycle[nc++] = x;
        x = mp[x];
    } while (x != term);
    for (i = 0; i < nc; i++) {
        unsigned char src = old[mp[cycle[i]]];
        v[cycle[i]] = inv ? (unsigned char)(src ^ 1) : src;
    }
}

}


