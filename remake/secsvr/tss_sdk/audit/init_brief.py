#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Emit a per-OUR-CU static-initialization reconstruction brief.

For every reconstructed TU: which ORIG CU(s) it covers, the ORIG init-block
call multiset, the referenced strings/data, the ORIG DWARF variables of that
CU, and whether our TU currently has an init block.

Usage: init_brief.py audit/report > audit/report/init_brief.md
"""
from __future__ import print_function

import json
import sys
from collections import Counter, defaultdict


def base(cu):
    return (cu or "").replace("\\", "/").rsplit("/", 1)[-1]


def main(argv):
    root = argv[1] if len(argv) > 1 else "audit/report"
    diff = json.load(open(root + "/diff.json"))
    orig = json.load(open("/tmp/orig_model.json"))
    ours = json.load(open("/tmp/our_model.json"))
    io = json.load(open(root + "/init_orig.json"))
    iu = json.load(open(root + "/init_ours.json"))

    # ORIG cu -> our cu(s): every reconstructed CU that emits a function of the
    # ORIG CU. One reconstructed file can cover several ORIG CUs (the
    # reconstruction splits original files into *_agent.cpp slices).
    per_our = defaultdict(set)
    for mangled, rec in ours["funcs"].items():
        orec = orig["funcs"].get(mangled)
        if orec is None:
            continue
        per_our[base(rec["cu"])].add(base(orec["cu"]))
    rev = defaultdict(set)
    for ucu, ocs in per_our.items():
        for ocu in ocs:
            rev[ocu].add(ucu)

    # ORIG vars per CU
    ovars = defaultdict(list)
    for a, lst in orig["vars"].items():
        for v in lst:
            ovars[base(v["cu"])].append(
                {"name": v["pretty"], "type": v["type"], "size": v["size"],
                 "addr": int(a)})

    # our init blocks per CU basename
    uinit = defaultdict(list)
    for cu, rows in iu["groups"].items():
        uinit[base(cu)].extend(rows)

    oinit = defaultdict(list)
    for cu, rows in io["groups"].items():
        oinit[base(cu)].extend(rows)

    # invert: our CU -> ORIG CUs
    per_our = defaultdict(set)
    for ocu, targets in rev.items():
        for t in targets:
            per_our[t].add(ocu)

    out = []
    add = out.append
    add("# Static-initialization reconstruction brief\n")
    add("Generated by `audit/init_brief.py`. For each reconstructed TU: the ORIG "
        "CU it covers, ORIG init-block call multiset, referenced strings, ORIG "
        "DWARF variables and the current state of our init block.\n")
    add("Recipe (verified by a controlled probe):\n")
    add("```cpp")
    add('#include "src/commlib/framework/comm_predefine.h"')
    add('#include "output/commlib/framework/release/include/comm_stat_define.h"')
    add("static std::ios_base::Init __ioinit;  // GCC 4.1 emitted this per TU; "
        "GCC 13 <iostream> no longer does")
    add("```")
    add("plus the TU-specific globals listed below, declared with the ORIG "
        "type/name and initialized with the ORIG constructor arguments.\n")

    # every our CU that has an ORIG mapping, plus unmapped ORIG TUs of interest
    all_our = sorted(set(per_our) | set(uinit))
    for ucu in all_our:
        ocs = sorted(per_our.get(ucu, set()))
        rows = uinit.get(ucu, [])
        add("## %s\n" % ucu)
        if not ocs:
            add("- ORIG CU: `<unmapped>`\n")
        for ocu in ocs:
            add("### ORIG CU `%s`\n" % ocu)
            v = ovars.get(ocu, [])
            add("- ORIG static variables (%d): %s\n" %
                (len(v), ", ".join("%s %s(%s)" % (x["name"], x["type"],
                                                  x["size"]) for x in v)))
            for r in oinit.get(ocu, []):
                cc = Counter(r.get("calls", []))
                add("- init target size %s, instructions %s\n" %
                    (r.get("target_size"), r.get("insn_count")))
                add("  - call multiset: `%s`\n" % dict(cc))
                strs = sorted({x["str"] for x in r.get("refs", [])
                               if x.get("str")})
                if strs:
                    add("  - strings (%d): %s\n" % (len(strs), strs[:40]))
                syms = sorted({x["sym"] for x in r.get("refs", [])
                               if x.get("sym")})
                if syms:
                    add("  - referenced symbols (%d): %s\n" %
                        (len(syms), syms[:40]))
                if r.get("imms"):
                    add("  - stack immediates: %s\n" % r["imms"][:40])
        if rows:
            for r in rows:
                cc = Counter(r.get("calls", []))
                add("- OUR init `%s` size=%s calls=`%s`\n" %
                    (r["sym"], r["size"], dict(cc)))
        else:
            add("- OUR init block: **absent**\n")
        add("")

    uncovered = sorted(ocu for ocu in oinit if ocu not in rev)
    add("## ORIG CUs with an init block but no reconstructed symbol\n")
    for ocu in uncovered:
        for r in oinit[ocu]:
            cc = Counter(r.get("calls", []))
            add("- `%s` target_size=%s calls=`%s`" %
                (ocu, r.get("target_size"), dict(cc)))
    add("")

    text = "\n".join(out) + "\n"
    if len(argv) > 2:
        open(argv[2], "w").write(text)
        print("wrote", argv[2], "cus=%d" % len(all_our))
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
