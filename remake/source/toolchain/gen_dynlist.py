#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the precise dynamic-list whitelist from ORIG's .dynsym definition set.

Rules (all evidenced in R19scanDYN/report.md):
  * source of truth = ORIG .dynsym entries with st_shndx != 0 (3017 names)
  * drop the ORIG-side obfuscated name `_ZS\\x0f\\x84\\x03\\x02Rb_tree...`
    (symtab proves the real name is _ZSt18_Rb_tree_incrementPKSt18_Rb_tree_node_base;
     the 4 bytes were overwritten in ORIG's .dynstr -> not reproducible)
  * strip `@VER` suffixes that `nm -D` appends (stdin/stdout/stderr@GLIBC_2.0)
Sentinel: aborts if the whitelist is empty or suspiciously small (< 2900).
Usage: gen_dynlist.py ORIG.syms.tsv OUT.dynlist
"""
import sys

def main():
    tsv, out = sys.argv[1], sys.argv[2]
    names = []
    for line in open(tsv):
        f = line.rstrip('\n').split('\t')
        if len(f) != 7:
            continue
        tab, name, bind, typ, shndx, val, size = f
        if tab != 'dynsym' or int(shndx) == 0:
            continue
        if any(ord(c) < 0x20 or ord(c) > 0x7e for c in name):
            print('skip non-printable ORIG name: %r' % name, file=sys.stderr)
            continue
        if '@' in name:
            base = name.split('@', 1)[0]
            print('strip version suffix: %s -> %s' % (name, base), file=sys.stderr)
            name = base
        names.append(name)
    names = sorted(set(names))
    if len(names) < 2900:
        sys.exit('FATAL sentinel: whitelist too small (%d) — refuse to write' % len(names))
    with open(out, 'w') as f:
        f.write('/* df_game_r dynamic export list — exact ORIG .dynsym definition set\n')
        f.write(' * generated by source/toolchain/gen_dynlist.py from the ORIG binary;\n')
        f.write(' * used as -Wl,--dynamic-list=<this file> (does NOT alter .symtab binding).\n')
        f.write(' * entries: %d */\n' % len(names))
        f.write('{\n')
        for n in names:
            f.write('  "%s";\n' % n)
        f.write('};\n')
    print('wrote %s with %d symbols' % (out, len(names)))

if __name__ == '__main__':
    main()
